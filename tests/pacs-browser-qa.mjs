// PACS browser QA — real interactive coverage for the New HR Collection's
// standalone Personnel Attendance Control System dashboard.
//
// PACS previously had static contract, route, a11y and SEO coverage only, so
// the doc claim "PACS + Recruitment Analytics browser QA" was not true for PACS.
// This suite drives the representative visitor flows in a real browser.
//
// Hardening rules for this file:
//   * every assertion tests a behaviour with an exact expected value taken from
//     the dashboard's own embedded synthetic dataset — never a shape check that
//     passes while the feature is broken;
//   * a check that cannot fail (a length > 0 on an always-non-empty string) is
//     treated as a bug, not a check;
//   * console.error() fails the suite unless it matches a documented, narrow
//     allowlist entry;
//   * the Excel import path is genuinely exercised with a synthetic workbook
//     generated by tests/fixtures/make-pacs-qa-fixture.mjs — no real employee
//     data, no dependency on the 1.5 MB sample, nothing leaving the browser.
import { execFileSync } from 'node:child_process';
import { rmSync } from 'node:fs';
import { chromium } from 'playwright';

const BASE = process.env.ANCIENT_WORLD_BASE_URL || 'http://127.0.0.1:4173';
const PACS = `${BASE}/analytics/dashboards/new-hr-collection/pacs/`;
const FIXTURE = '/tmp/pacs-qa-fixture.xlsx';

// Facts taken from the dashboard's embedded synthetic sample so the assertions
// can name exact expected values. If the sample changes, these must change too
// — that is the point: the suite should fail loudly rather than drift.
const EXPECTED = {
  staffCount: 120,
  orgCount: 25,
  searchPerson: { no: '1073', name: 'AARON GRANVILLE', org: 'Aeronautical Revenue & Billing Directorate' },
  orgStaffTotal: 4,
  orgStaffMember: { no: '1023', name: 'David Chambers' },
  fixture: { staff: 3, records: 9, org: 'QA Synthetic Department', dateMin: '2026-09-01', dateMax: '2026-09-03' },
  calendarQuick: { all: 'all', leave: 'annual_leave' },
  defaultStart: '08:00',
  probeRuleDate: '2026-12-24',
};

// Documented, narrow console-error allowlist. Each entry must say why the
// browser emits it and why it is not a product defect. Anything unlisted fails.
const CONSOLE_ERROR_ALLOWLIST = [
  {
    match: /Failed to load resource.*favicon/i,
    why: 'The PACS route declares no favicon link, so the browser requests /favicon.ico itself. Not a PACS defect.',
  },
];

const results = [];
const check = (name, ok, detail = '') => {
  results.push({ name, ok, detail });
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? ` — ${detail}` : ''}`);
};

execFileSync('node', ['tests/fixtures/make-pacs-qa-fixture.mjs', FIXTURE], { stdio: 'pipe' });

const browser = await chromium.launch({ headless: true });
const pageErrors = [];
const consoleErrors = [];

function recordConsoleError(raw, width) {
  const allowed = CONSOLE_ERROR_ALLOWLIST.find((rule) => rule.match.test(raw));
  if (allowed) {
    check(`allowlisted console error: ${allowed.match.source}`, true, allowed.why.slice(0, 60));
    return;
  }
  consoleErrors.push(`${width}px: ${raw}`);
}

async function withPage(viewport, fn) {
  const context = await browser.newContext({ viewport });
  const page = await context.newPage();
  page.on('pageerror', (e) => pageErrors.push(`${viewport.width}px: ${e.message}`));
  page.on('console', (m) => {
    if (m.type() === 'error') recordConsoleError(m.text(), viewport.width);
  });
  try {
    await fn(page);
  } finally {
    await context.close();
  }
}

const text = (page, sel) => page.$eval(sel, (el) => el.textContent.trim()).catch(() => '');
const visible = (page, sel) =>
  page.$eval(sel, (el) => {
    const s = getComputedStyle(el);
    return s.display !== 'none' && s.visibility !== 'hidden' && el.offsetParent !== null;
  }).catch(() => false);
const cardCount = (page, sel) => page.$$eval(`${sel} > *`, (n) => n.length).catch(() => 0);
const matrixRows = (page) =>
  page
    .$$eval('#matrixWrap table tbody tr', (n) => n.map((r) => r.textContent.replace(/\s+/g, ' ').trim()))
    .catch(() => []);
const calRows = (page) => page.$$eval('#calendarDetailTable tbody tr', (n) => n.length).catch(() => 0);

// ---------------------------------------------------------------- desktop
await withPage({ width: 1440, height: 900 }, async (page) => {
  const response = await page.goto(PACS, { waitUntil: 'load', timeout: 60000 });
  check('dashboard responds 200', response?.status() === 200, `status=${response?.status()}`);

  await page.waitForSelector('#kpiGrid > *', { timeout: 30000 });
  check('initial dashboard state is usable', (await cardCount(page, '#kpiGrid')) > 0);

  // The hero states the real dataset size, so assert that exact number.
  const heroStats = await text(page, '#heroStats');
  check(
    'hero reports the embedded dataset size',
    heroStats.includes(`${EXPECTED.staffCount} Monitored Staff`),
    heroStats,
  );

  // --- global period filter.
  // heroRange legitimately spans the whole dataset no matter which month is
  // selected, so assert the state the control actually owns: the selected
  // value, the KPI grid and the organization matrix figures.
  const options = await page.$$eval('#globalPeriod option', (o) => o.map((x) => x.value));
  check('period filter offers the dataset months', options.length > 1, options.join(','));

  const before = {
    kpi: await text(page, '#kpiGrid'),
    rows: await matrixRows(page),
    selected: await page.inputValue('#globalPeriod'),
  };
  const other = options.find((o) => o !== before.selected);
  await page.selectOption('#globalPeriod', other);
  await page.waitForTimeout(1200);
  const after = {
    kpi: await text(page, '#kpiGrid'),
    rows: await matrixRows(page),
    selected: await page.inputValue('#globalPeriod'),
  };
  check('period selection is applied to the control', after.selected === other, `${before.selected} -> ${after.selected}`);
  check('period change alters KPI values', after.kpi !== before.kpi, 'KPI grid content differs');
  check(
    'period change alters organization matrix values',
    after.rows.length === before.rows.length && after.rows.join('|') !== before.rows.join('|'),
    `${before.rows[0]?.slice(0, 44)} -> ${after.rows[0]?.slice(0, 44)}`,
  );
  await page.selectOption('#globalPeriod', before.selected);
  await page.waitForTimeout(1000);
  check('period selection restores the original state', (await text(page, '#kpiGrid')) === before.kpi);

  // --- overview search: a real person from the embedded dataset.
  const allRows = await matrixRows(page);
  check('overview lists every organization before search', allRows.length === EXPECTED.orgCount, `${allRows.length} rows`);

  await page.fill('#searchFilter', EXPECTED.searchPerson.name);
  await page.waitForTimeout(1000);
  const searched = await matrixRows(page);
  check(
    'employee search narrows the matrix to the matching organization',
    searched.length === 1 && searched[0].includes(EXPECTED.searchPerson.org),
    `${searched.length} row(s): ${searched[0]?.slice(0, 58) ?? 'none'}`,
  );
  check('employee search result is strictly smaller than the full list', searched.length < allRows.length, `${allRows.length} -> ${searched.length}`);

  await page.fill('#searchFilter', '');
  await page.waitForTimeout(1000);
  check('clearing the search restores every organization', (await matrixRows(page)).length === EXPECTED.orgCount);

  // --- organization selection, then the organization detail view.
  await page.selectOption('#orgFilter', EXPECTED.searchPerson.org);
  await page.waitForTimeout(900);
  check('organization filter accepts a real organization', (await page.inputValue('#orgFilter')) === EXPECTED.searchPerson.org);

  await page.click('[data-view="organizationView"]');
  await page.waitForTimeout(1000);
  check('organization view opens', await visible(page, '#organizationView'));
  check('organization view renders its KPI grid', (await cardCount(page, '#orgKpiGrid')) > 0);

  // #orgSearchInput filters organizations; #orgStaffSelect filters the people
  // inside the chosen organization. Selecting a person is what narrows the
  // ledger, so that is what the assertion follows.
  const staffOptions = await page.$$eval('#orgStaffSelect option', (o) => o.map((x) => x.value).filter(Boolean));
  check(
    'organization staff list matches the embedded membership',
    staffOptions.length === EXPECTED.orgStaffTotal,
    `${staffOptions.length} staff options`,
  );

  const staffLabels = await page.$$eval('#orgStaffSelect option', (o) => o.map((x) => x.textContent.trim()));
  check(
    'staff options identify people by name and id',
    staffLabels.some((t) => t.includes(EXPECTED.orgStaffMember.name) && t.includes(EXPECTED.orgStaffMember.no)),
    staffLabels.join(' | ').slice(0, 88),
  );

  const orgAll = await text(page, '#orgDetailDescription');
  check('organization ledger reports all staff before filtering', orgAll.startsWith(`${EXPECTED.orgStaffTotal} staff`), orgAll);

  await page.selectOption('#orgStaffSelect', EXPECTED.orgStaffMember.no);
  await page.waitForTimeout(1000);
  const orgOne = await text(page, '#orgDetailDescription');
  check('selecting one staff member narrows the ledger to that person', orgOne.startsWith('1 staff'), `"${orgAll}" -> "${orgOne}"`);
  check('organization day detail renders rows', (await cardCount(page, '#orgDayTable > *')) > 0);
  check(
    'day-filter reset is disabled while no day filter is active',
    (await page.$eval('#clearOrgDayFiltersBtn', (b) => b.disabled)) === true,
  );

  // --- person view: search narrows, selection renders.
  await page.click('[data-view="personView"]');
  await page.waitForTimeout(1000);
  check('person view opens', await visible(page, '#personView'));

  // The person selector holds exactly one option per monitored employee — no
  // placeholder row — so the expected count is the staff count itself.
  const personOptions = await page.$$eval('#personSelect option', (o) => o.length);
  check('person selector lists the full staff set', personOptions === EXPECTED.staffCount, `${personOptions} options`);

  await page.fill('#personSearch', 'AARON');
  await page.waitForTimeout(1000);
  const narrowed = await page.$$eval('#personSelect option', (o) => o.length);
  check('person search narrows the selector to matches only', narrowed === 1 && narrowed < personOptions, `${personOptions} -> ${narrowed}`);
  check(
    'person search result is the expected person',
    (await page.$$eval('#personSelect option', (o) => o.map((x) => x.textContent).join(' '))).includes('Aaron Granville (1073)'),
  );

  await page.fill('#personSearch', '');
  await page.waitForTimeout(1000);
  check('clearing person search restores the full set', (await page.$$eval('#personSelect option', (o) => o.length)) === personOptions);

  await page.selectOption('#personSelect', EXPECTED.searchPerson.no);
  await page.waitForTimeout(1000);
  check('selecting a person renders their KPI cards', (await cardCount(page, '#personKpiGrid')) > 0);
  check('person day table renders rows', (await cardCount(page, '#personDayTable > *')) > 0);

  // --- calendar quick filters: click one and observe the real state change.
  await page.click('[data-view="calendarDetailView"]');
  await page.waitForTimeout(1200);
  check('calendar detail view opens', await visible(page, '#calendarDetailView'));
  check('calendar detail has a filter-reset control', !!(await page.$('#clearCalendarDetailFiltersBtn')));

  const quickCounts = await page.$$eval('#calendarQuickFilters > *', (n) =>
    Object.fromEntries(n.map((x) => [x.dataset.calendarQuick, x.textContent.trim()])),
  );
  const allCount = Number(quickCounts[EXPECTED.calendarQuick.all].replace(/\D/g, ''));
  const leaveCount = Number(quickCounts[EXPECTED.calendarQuick.leave].replace(/\D/g, ''));
  check(
    'calendar quick filters expose strictly ordered counts',
    allCount > leaveCount && leaveCount > 0,
    `all=${allCount}, annual_leave=${leaveCount}`,
  );

  const rowsAll = await calRows(page);
  check('calendar detail shows the full row set for "All"', rowsAll === allCount, `rows=${rowsAll}, label=${allCount}`);

  await page.click(`#calendarQuickFilters [data-calendar-quick="${EXPECTED.calendarQuick.leave}"]`);
  await page.waitForTimeout(1200);
  const leaveActive = await page.$eval(
    `#calendarQuickFilters [data-calendar-quick="${EXPECTED.calendarQuick.leave}"]`,
    (b) => b.classList.contains('active'),
  );
  const rowsLeave = await calRows(page);
  check('a quick filter becomes active when clicked', leaveActive === true);
  check('an active quick filter narrows the result set', rowsLeave === leaveCount && rowsLeave < rowsAll, `all=${rowsAll} -> leave=${rowsLeave}`);

  await page.click(`#calendarQuickFilters [data-calendar-quick="${EXPECTED.calendarQuick.all}"]`);
  await page.waitForTimeout(1200);
  check('returning to "All" restores the full row set', (await calRows(page)) === rowsAll);

  // --- settings: calendar rules and workday times.
  await page.click('[data-view="settingsView"]');
  await page.waitForTimeout(1000);
  check('settings view opens', await visible(page, '#settingsView'));
  check('built-in calendar rules are listed', (await cardCount(page, '#calBuiltinTable tbody > tr')) > 0);

  const categories = await page.$$eval('#calNewCategory option', (o) => o.map((x) => x.value).filter(Boolean));
  check('calendar categories are a fixed set', categories.length > 0, categories.join(' / '));

  await page.fill('#calNewDate', EXPECTED.probeRuleDate);
  await page.selectOption('#calNewCategory', categories[0]);
  await page.fill('#calNewHours', '8');
  await page.fill('#calNewDesc', 'created by browser QA');
  await page.click('#calAddBtn');
  await page.waitForTimeout(1000);
  check('adding a calendar rule updates the custom table', (await text(page, '#calCustomTable')).includes(EXPECTED.probeRuleDate));

  // Both reset controls are confirm()-guarded by design; accept the dialog.
  page.once('dialog', (d) => d.accept());
  await page.click('#calResetBtn');
  await page.waitForTimeout(1000);
  check('reset clears the added calendar rule', !(await text(page, '#calCustomTable')).includes(EXPECTED.probeRuleDate));

  const startBefore = await page.inputValue('#setStart');
  check('settings exposes the default workday start', startBefore === EXPECTED.defaultStart, `start=${startBefore}`);

  await page.fill('#setStart', '09:15');
  await page.click('#saveSettingsBtn');
  await page.waitForTimeout(1000);
  check('saving settings reports success', (await text(page, '#settingsStatus')).includes('saved'), await text(page, '#settingsStatus'));
  check('saved settings value is reflected in the UI', (await page.inputValue('#setStart')) === '09:15');

  page.once('dialog', (d) => d.accept());
  await page.click('#resetSettingsBtn');
  await page.waitForTimeout(1000);
  check('reset restores the default workday start', (await page.inputValue('#setStart')) === startBefore, `restored=${await page.inputValue('#setStart')}`);

  // --- calculation rules view.
  await page.click('[data-view="rulesView"]');
  await page.waitForTimeout(900);
  check('calculation-rules view opens', await visible(page, '#rulesView'));
  // The rules are the published calculation contract: thresholds, shift
  // boundaries and grace periods. Assert the real defaults, not just "non-empty".
  const rulesText = (await text(page, '#rulesContent')).replace(/\s+/g, ' ');
  check(
    'calculation rules state the published shift and grace defaults',
    rulesText.includes('Shift start time: 08:00') &&
      rulesText.includes('Shift end time: 17:30') &&
      rulesText.includes('Arrival tolerance: 30 minutes'),
    rulesText.slice(0, 90),
  );

  // --- real Excel import with a synthetic workbook.
  const heroBefore = await text(page, '#heroStats');
  await page.click('[data-view="importView"]');
  await page.waitForTimeout(600);
  check('import view opens', await visible(page, '#importView'));
  check('Excel file input is present', !!(await page.$('#pacsExcelFileInput')));
  check('dropzone is present', !!(await page.$('#pacsDropzone')));

  await page.setInputFiles('#pacsExcelFileInput', FIXTURE);
  await page.waitForFunction(
    () => /loaded successfully|Upload Failed/.test(document.getElementById('pacsUploadStatus')?.textContent || ''),
    null,
    { timeout: 30000 },
  );
  const uploadStatus = await text(page, '#pacsUploadStatus');
  check('the synthetic workbook is accepted', uploadStatus.includes('loaded successfully'), uploadStatus.slice(0, 88));
  check('the import reports the parsed staff count', uploadStatus.includes(`${EXPECTED.fixture.staff} staff`), uploadStatus.slice(0, 88));
  check(
    'the import reports the parsed record count and date range',
    uploadStatus.includes(`${EXPECTED.fixture.records} records`) &&
      uploadStatus.includes(EXPECTED.fixture.dateMin) &&
      uploadStatus.includes(EXPECTED.fixture.dateMax),
    uploadStatus.slice(0, 120),
  );

  const heroAfter = await text(page, '#heroStats');
  check(
    'importing replaces the dashboard dataset',
    heroAfter.includes(`${EXPECTED.fixture.staff} Monitored Staff`) && heroAfter !== heroBefore,
    `"${heroBefore}" -> "${heroAfter}"`,
  );
  const orgOptionsAfter = await page.$$eval('#orgFilter option', (o) => o.map((x) => x.textContent.trim()));
  // Compare case-insensitively: the dashboard applies a CSS text transform to
  // organization names, so the rendered label is not the stored spelling.
  const orgText = orgOptionsAfter.join(' | ').toLowerCase();
  check(
    'the imported organization replaces the original ones',
    orgOptionsAfter.length === 2 && orgText.includes(EXPECTED.fixture.org.toLowerCase()),
    orgOptionsAfter.join(' | '),
  );

  await page.click('[data-view="dashboardView"]');
  await page.waitForTimeout(800);
  check('CSV export controls exist', !!(await page.$('#downloadCsvBtn')) && !!(await page.$('#downloadOrgCsvBtn')));

  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  check('no horizontal overflow at 1440px', overflow <= 2, `overflow=${overflow}px`);
});

// ---------------------------------------------------------------- narrow
await withPage({ width: 390, height: 844 }, async (page) => {
  await page.goto(PACS, { waitUntil: 'load', timeout: 60000 });
  await page.waitForSelector('#kpiGrid > *', { timeout: 30000 });

  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  check('narrow viewport does not overflow', overflow <= 2, `overflow=${overflow}px at 390px`);

  const tabs = await page.$$('#viewTabs .view-tab');
  check('all seven view tabs are present on mobile', tabs.length === 7, `${tabs.length} tabs`);
  await tabs[2].click();
  await page.waitForTimeout(800);
  check('a different view opens on a narrow viewport', await visible(page, '#personView'));
});

await browser.close();
rmSync(FIXTURE, { force: true });

// ---------------------------------------------------------------- report
const failed = results.filter((r) => !r.ok);
console.log(`\nPACS browser QA: ${results.length - failed.length}/${results.length} checks passed`);
if (pageErrors.length) console.log(`\nuncaught page errors: ${JSON.stringify(pageErrors, null, 2)}`);
if (consoleErrors.length) console.log(`\nunexpected console errors: ${JSON.stringify(consoleErrors, null, 2)}`);
if (failed.length) console.log(`\nfailed checks: ${failed.map((f) => f.name).join('; ')}`);

if (pageErrors.length || consoleErrors.length || failed.length) process.exit(1);
console.log('PACS browser QA passed.');
