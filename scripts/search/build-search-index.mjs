import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ANALYTICS_SETS } from '../../frontend/analytics/catalog.js';

const outputPath=new URL('../../frontend/js/v3/search-index.generated.js',import.meta.url);
const newsPath=new URL('../../frontend/news/index.json',import.meta.url);
const check=process.argv.includes('--check');

function freezeLiteral(value){
  if(Array.isArray(value))return `Object.freeze([${value.map(freezeLiteral).join(',')}])`;
  if(value&&typeof value==='object')return `Object.freeze({${Object.entries(value).map(([key,item])=>`${JSON.stringify(key)}:${freezeLiteral(item)}`).join(',')}})`;
  return JSON.stringify(value);
}

function newsEntries(){
  const index=JSON.parse(readFileSync(newsPath,'utf8'));
  return index.items.map((item)=>{
    const date=String(item.publishedAt||'').slice(0,10);
    const prefix=`${date}-`;
    const slug=String(item.id||'').startsWith(prefix)?String(item.id).slice(prefix.length):String(item.id||'');
    return {
      type:'content',
      id:`news:${item.id}`,
      kind:'News',
      label:item.title,
      description:item.summary,
      href:`/news/${date}/${slug}/`,
      icon:'/assets/icons/aizanoi-news.svg',
      keywords:['news',item.category,...(item.tags||[])],
    };
  });
}

function analyticsEntries(){
  const entries=[];
  for(const set of ANALYTICS_SETS){
    entries.push({
      type:'content',
      id:`analytics-set:${set.id}`,
      kind:'Analytics',
      label:set.title,
      description:set.description||set.summary,
      href:set.landing,
      icon:'/assets/icons/aizanoi-dashboards.svg',
      keywords:['analytics','dashboard',set.title,set.accent,set.interfaceLanguage].filter(Boolean),
    });
    for(const [index,dashboard] of set.dashboards.entries()){
      entries.push({
        type:'content',
        id:`analytics:${set.id}:${index}`,
        kind:'Analytics',
        label:dashboard.title,
        description:dashboard.summary,
        href:dashboard.href,
        icon:'/assets/icons/aizanoi-dashboards.svg',
        keywords:['analytics','dashboard',set.title,dashboard.title],
      });
    }
  }
  return entries;
}

const entries=[...newsEntries(),...analyticsEntries()]
  .sort((a,b)=>a.id.localeCompare(b.id));
export const SEARCH_INDEX_SOURCE=`// Generated by scripts/search/build-search-index.mjs. Do not edit manually.\nexport const STATIC_SEARCH_ENTRIES=${freezeLiteral(entries)};\n`;

export function normalizeLineEndings(value){
  return value.replace(/\r\n?/g,'\n');
}

export function checkSearchIndex(output=outputPath){
  const current=readFileSync(output,'utf8');
  if(normalizeLineEndings(current)!==normalizeLineEndings(SEARCH_INDEX_SOURCE)){
    throw new Error('Static search index is stale. Run: node scripts/search/build-search-index.mjs');
  }
  return true;
}

export function runSearchIndex({checkMode=check,output=outputPath}={}){
  if(checkMode){
    try{
      checkSearchIndex(output);
    }catch(error){
      console.error(error.message);
      process.exitCode=1;
      return;
    }
    console.log(`Static search index is current (${entries.length} entries).`);
  }else{
    writeFileSync(output,SEARCH_INDEX_SOURCE);
    console.log(`Static search index wrote ${entries.length} entries.`);
  }
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  runSearchIndex();
}
